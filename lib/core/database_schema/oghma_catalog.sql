CREATE TABLE IF NOT EXISTS public.oghma_audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    contract_version text NOT NULL,
    request_type text NOT NULL DEFAULT '',
    input text NOT NULL DEFAULT '',
    status text NOT NULL,
    grounded jsonb NOT NULL DEFAULT '{}'::jsonb,
    access jsonb NOT NULL DEFAULT '[]'::jsonb,
    fallback jsonb NOT NULL DEFAULT '{}'::jsonb,
    settings jsonb NOT NULL DEFAULT '{}'::jsonb,
    catalog_version text,
    catalog_manifest_sha256 character(64),
    latency_ms double precision NOT NULL DEFAULT 0,
    prompt_sha256 character(64)
);
CREATE INDEX IF NOT EXISTS oghma_audit_created_at_idx ON public.oghma_audit(created_at DESC);
CREATE INDEX IF NOT EXISTS oghma_audit_status_idx ON public.oghma_audit(status, created_at DESC);

