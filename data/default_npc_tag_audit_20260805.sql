-- Apply the complete semantic tag recommendations from the GLM audit.
-- merchant and child are excluded here and applied from verified evidence below.
CREATE OR REPLACE FUNCTION pg_temp.chim_apply_csv_tag_changes(
    current_tags text,
    add_tags text[],
    remove_tags text[]
)
RETURNS text
LANGUAGE sql
IMMUTABLE
AS $$
    SELECT COALESCE(string_agg(tag, ', ' ORDER BY tag), '')
      FROM (
            SELECT DISTINCT lower(btrim(value)) AS tag
              FROM unnest(string_to_array(COALESCE(current_tags, ''), ',')) AS value
             WHERE btrim(value) <> ''
               AND NOT (lower(btrim(value)) = ANY(COALESCE(remove_tags, ARRAY[]::text[])))
            UNION
            SELECT DISTINCT lower(btrim(value)) AS tag
              FROM unnest(COALESCE(add_tags, ARRAY[]::text[])) AS value
             WHERE btrim(value) <> ''
      ) AS normalized_tags;
$$;

