CREATE OR REPLACE FUNCTION pg_temp.chim_merge_canonical_regions(current_tags text, canonical_tags text)
RETURNS text LANGUAGE sql IMMUTABLE AS $$
    WITH region_tags(tag) AS (VALUES
        ('eastmarch'),('falkreath'),('haafingar'),('hjaalmarch'),('pale'),
        ('reach'),('rift'),('solstheim'),('whiterun'),('winterhold')
    ), candidates AS (
        SELECT lower(btrim(value)) AS tag, 0 AS source_order, ordinal
          FROM regexp_split_to_table(COALESCE(current_tags, ''), '\s*,\s*') WITH ORDINALITY AS item(value, ordinal)
         WHERE btrim(value) <> '' AND lower(btrim(value)) NOT IN (SELECT tag FROM region_tags)
           AND lower(btrim(value)) NOT IN ('common', 'esoteric', 'skyrimall')
        UNION ALL
        SELECT lower(btrim(value)) AS tag, 1 AS source_order, ordinal
          FROM regexp_split_to_table(COALESCE(canonical_tags, ''), '\s*,\s*') WITH ORDINALITY AS item(value, ordinal)
         WHERE lower(btrim(value)) IN (SELECT tag FROM region_tags)
    ), deduplicated AS (
        SELECT tag, min(source_order) AS source_order, min(ordinal) AS ordinal
          FROM candidates GROUP BY tag
    )
    SELECT COALESCE(string_agg(tag, ', ' ORDER BY source_order, ordinal), '') FROM deduplicated;
$$;
UPDATE public.core_npc_master AS master
   SET oghma_knowledge_tags = pg_temp.chim_merge_canonical_regions(master.oghma_knowledge_tags, canonical.tags)
  FROM canonical_npc_knowledge_tags AS canonical
 WHERE canonical.npc_name = trim(both '_' from lower(regexp_replace(master.npc_name, '[^A-Za-z0-9]+', '_', 'g')));
CREATE OR REPLACE FUNCTION pg_temp.chim_strip_article_markers(current_tags text)
RETURNS text LANGUAGE sql IMMUTABLE AS $$
    SELECT COALESCE(string_agg(tag, ', ' ORDER BY ordinal), '')
      FROM (
        SELECT lower(btrim(value)) AS tag, min(ordinal) AS ordinal
          FROM regexp_split_to_table(COALESCE(current_tags, ''), '\s*[,|;]\s*') WITH ORDINALITY AS item(value, ordinal)
         WHERE btrim(value) <> '' AND lower(btrim(value)) NOT IN ('common', 'esoteric', 'skyrimall')
         GROUP BY lower(btrim(value))
      ) AS cleaned;
$$;
UPDATE public.bio_templates
   SET oghma_knowledge_tags = pg_temp.chim_strip_article_markers(oghma_knowledge_tags);
UPDATE public.bio_templates_custom
   SET oghma_knowledge_tags = pg_temp.chim_strip_article_markers(oghma_knowledge_tags);
UPDATE public.core_npc_master
   SET oghma_knowledge_tags = pg_temp.chim_strip_article_markers(oghma_knowledge_tags);
COMMIT;
